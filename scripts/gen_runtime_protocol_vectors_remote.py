"""Regenerate src/browser/runtimeProtocol/vectors/v1-remote.json — the WP-3
remote additions to the protocol v1 conformance vectors.

    python scripts/gen_runtime_protocol_vectors_remote.py   # from the nexus_web root (any cwd works)

Same independence rule as gen_runtime_protocol_vectors.py: the values here are
computed with the Python standard library (hmac, hashlib, base64), never the TS
side, so the TS implementations of the text blob encoding (blobText.ts) and the
pair proof (pairProof.ts) are cross-checked, not self-graded. Never hand-edit
the JSON.

Two families of vectors:
  - encodedTextB64: the SAME blob chunk as v1.json's blobChunks, carried as the
    text message a WebSocket sends — 'B' + base64(encodeBlobChunk(header, bytes)).
    The C++ listener (WP-5) speaks text only, so this is the on-wire form.
  - pairProofs: base64url(HMAC-SHA256(base64urlDecode(pairSecret),
    utf8(nonce + '\n' + clientId))) — the frozen proof of frames.ts.
"""
import base64
import hashlib
import hmac
import json
import pathlib
import struct

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "browser" / "runtimeProtocol" / "vectors" / "v1-remote.json"


def chunk_bytes(header, payload_hex):
    """The same layout as gen_runtime_protocol_vectors.py's chunk_hex, as bytes."""
    hdr = json.dumps(
        {"id": header["id"], "index": header["index"], "last": header["last"]},
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")
    return struct.pack(">I", len(hdr)) + hdr + bytes.fromhex(payload_hex)


def b64u(data):
    return base64.urlsafe_b64encode(data).decode("ascii").rstrip("=")


# The same four blob fixtures as v1.json, so a reader can see the two forms
# carry identical bytes.
blob_text = []
for name, header, payload_hex in [
    ("single-chunk-last", {"id": "blob-1", "index": 0, "last": True}, "00ff10"),
    ("middle-chunk", {"id": "blob-9", "index": 7, "last": False}, "deadbeefcafebabe"),
    ("empty-final-chunk", {"id": "blob-9", "index": 8, "last": True}, ""),
    ("utf8-id", {"id": "附件-1", "index": 0, "last": True}, "01"),
]:
    raw = chunk_bytes(header, payload_hex)
    blob_text.append({
        "name": name,
        "header": header,
        "bytesHex": payload_hex,
        "encodedTextB64": "B" + base64.b64encode(raw).decode("ascii"),
    })

# pairProof = base64url(HMAC-SHA256(base64urlDecode(secret), utf8(nonce + '\n' + clientId))).
pair_proofs = []
for name, secret_b64u, nonce, client_id in [
    ("proof-1", b64u(bytes(range(32))), "nonce-3f9c0a", "install-7f3a"),
    ("proof-utf8-client", b64u(b"\xde\xad\xbe\xef" * 8), "n-1", "设备-91c0"),
]:
    secret = base64.urlsafe_b64decode(secret_b64u + "=" * (-len(secret_b64u) % 4))
    proof = hmac.new(secret, (nonce + "\n" + client_id).encode("utf-8"), hashlib.sha256).digest()
    pair_proofs.append({
        "name": name,
        "pairSecret": secret_b64u,
        "nonce": nonce,
        "clientId": client_id,
        "proof": b64u(proof),
    })

doc = {
    "$comment": ("Remote (WP-3) additions to the UI <-> Runtime protocol v1 conformance vectors: the "
                 "text blob encoding (encodedTextB64 = 'B' + base64 of the same encodeBlobChunk bytes "
                 "v1.json pins) and the pair proof. GENERATED by "
                 "scripts/gen_runtime_protocol_vectors_remote.py (an independent Python encoder using "
                 "hmac/hashlib/base64) — edit that script and re-run it; never edit this file by hand. "
                 "pairProof.ts is NOT mirrored into custom_browser."),
    "protocol": 1,
    "blobText": blob_text,
    "pairProofs": pair_proofs,
}


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes((json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes): {len(blob_text)} blobText, {len(pair_proofs)} pairProofs")


if __name__ == "__main__":
    main()
