import type { NexusModelPattern } from './types'

const OPENAI_DATE_SUFFIX = '(?:-\\d{4}-\\d{2}-\\d{2})?'
const ANTHROPIC_DATE_SUFFIX = '(?:-\\d{8})?'

function createOptionalSuffixPattern(
  pattern: string,
  optionalSuffix = '',
): RegExp {
  return new RegExp(`^${pattern}${optionalSuffix}$`, 'i')
}

/** `text` as a literal inside a RegExp source. */
export function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

export function createOpenAiModelPattern(pattern: string): RegExp {
  return createOptionalSuffixPattern(pattern, OPENAI_DATE_SUFFIX)
}

export function createAnthropicModelPattern(pattern: string): RegExp {
  return createOptionalSuffixPattern(pattern, ANTHROPIC_DATE_SUFFIX)
}

export function createExactModelPattern(pattern: string): RegExp {
  return createOptionalSuffixPattern(pattern)
}

/**
 * The concrete model id a catalog pattern stands for: a plain string as it
 * is, a regex built by the helpers above with its anchors and optional date
 * suffix stripped. Undefined when the pattern is regex-only (groups,
 * alternation, classes, quantifiers) and no single id can be read off it.
 * The host flattens the same way (`DeriveTsModelId`, nexus_llm_host.cc).
 */
export function deriveCanonicalModelId(
  pattern: NexusModelPattern,
): string | undefined {
  if (typeof pattern === 'string') {
    return pattern
  }

  const source = pattern.source
  // Strip common anchors and the optional date suffixes generated by our
  // pattern helpers.
  const stripped = source
    .replace(/^\^/, '')
    .replace(/\$$/, '')
    .replace(/\(\?:-\\d\{4\}-\\d\{2\}-\\d\{2}\)\?$/, '')
    .replace(/\(\?:-\\d\{8}\)\?$/, '')

  // If anything non-literal remains (groups, alternation, char classes,
  // quantifiers), we cannot safely use it as a model id.
  if (/[()[\]{}|?+*]/.test(stripped)) {
    return undefined
  }

  return stripped.replace(/\\(.)/g, '$1')
}
