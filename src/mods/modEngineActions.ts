/** Why a Button's `action` is refused, or null when the engine takes it. */
export function buttonActionProblem(action: unknown): string | null {
  if (action === undefined) return null
  if (typeof action !== 'string' || !BUTTON_ACTIONS.has(action)) {
    return `Button's action ${JSON.stringify(action)} is not one of the engine's keybinding actions`
  }
  if (RESERVED_BUTTON_ACTIONS.has(action)) return `Button's action "${action}" is the engine's alone`
  return null
}
